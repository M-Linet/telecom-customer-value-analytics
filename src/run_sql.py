"""Execute every named query in the sql/ folder and save the results.

A query block starts with a line `-- @query <name>`; the comment lines that follow become its
description. Results go to reports/sql_outputs/<name>.csv, and reports/sql_outputs/INDEX.md lists
each query with its row count and a preview, so every number in the report traces back to SQL.

    python -m src.run_sql                 # all analysis files
    python -m src.run_sql 07_inventory    # files whose name contains the text
"""
from __future__ import annotations

import re
import sys
import time
from dataclasses import dataclass
from pathlib import Path

import pandas as pd
from sqlalchemy import text

from src.data_loader import PROJECT_ROOT, SQL_DIR, get_engine

OUT = PROJECT_ROOT / "reports" / "sql_outputs"
QUERY_FILES = ["02_data_quality_checks.sql", "04_customer_value.sql", "05_retention.sql",
               "06_customer_experience.sql", "07_strategy.sql"]


@dataclass
class NamedQuery:
    file: str
    name: str
    description: str
    sql: str


def parse_sql_file(path: Path) -> list[NamedQuery]:
    blocks = re.split(r"^-- @query\s+", path.read_text(), flags=re.M)[1:]
    out = []
    for b in blocks:
        name, _, body = b.partition("\n")
        desc = []
        for line in body.splitlines():
            if line.startswith("--"):
                desc.append(line.lstrip("- ").rstrip())
            elif line.strip():
                break
        sql = body.strip().rstrip(";")
        out.append(NamedQuery(path.name, name.strip(), " ".join(d for d in desc if d), sql))
    return out


def run(filter_text: str | None = None) -> list[dict]:
    eng = get_engine()
    OUT.mkdir(parents=True, exist_ok=True)
    results = []
    for f in QUERY_FILES:
        if filter_text and filter_text not in f:
            continue
        for q in parse_sql_file(SQL_DIR / f):
            t0 = time.time()
            with eng.connect() as c:
                df = pd.read_sql(text(q.sql), c)
            df.to_csv(OUT / f"{q.name}.csv", index=False)
            results.append({"file": q.file, "name": q.name, "rows": len(df), "seconds": round(time.time() - t0, 2),
                            "description": q.description, "preview": df.head(8)})
            print(f"{q.file:<32} {q.name:<45} rows={len(df):>6}  {time.time()-t0:5.2f}s")
    if not filter_text:
        write_index(results)
    return results


def write_index(results: list[dict]) -> None:
    lines = ["# SQL output index", "",
             "Generated by `python -m src.run_sql`. Each section is one named query; the full result is in the CSV.", ""]
    for r in results:
        lines += [f"## `{r['name']}` ({r['file']})", "", r["description"], "",
                  f"Rows: {r['rows']}. Runtime: {r['seconds']} s. File: `{r['name']}.csv`", "",
                  r["preview"].to_markdown(index=False, floatfmt=",.2f") if len(r["preview"]) else "_(no rows)_", ""]
    (OUT / "INDEX.md").write_text("\n".join(lines))


if __name__ == "__main__":
    run(sys.argv[1] if len(sys.argv) > 1 else None)
